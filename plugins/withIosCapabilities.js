// iOS entitlements the app needs on real iPhones, which nothing else in the build adds:
// - aps-environment: APNs push. The app registers its APNs device token
//   (getDevicePushTokenAsync, push_provider 'apns'); without this iOS never issues one.
//   Xcode rewrites it to "production" when exporting for App Store / TestFlight.
// - App Attest: App Check's iOS provider (appAttestWithDeviceCheckFallback in
//   src/lib/appCheck.ts). Without it every attestation falls back to DeviceCheck.
// Plus ITSAppUsesNonExemptEncryption = false (HTTPS only), so App Store Connect doesn't
// hold every TestFlight build for an export-compliance answer.
// ios/ is generated by `expo prebuild`, so this is a config plugin.
const { withEntitlementsPlist, withInfoPlist } = require('expo/config-plugins');

module.exports = function withIosCapabilities(config) {
  config = withEntitlementsPlist(config, (cfg) => {
    cfg.modResults['aps-environment'] = cfg.modResults['aps-environment'] ?? 'development';
    cfg.modResults['com.apple.developer.devicecheck.appattest-environment'] = 'production';
    return cfg;
  });
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.ITSAppUsesNonExemptEncryption = false;
    return cfg;
  });
};
